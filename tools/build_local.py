"""Generate classic scripts for direct file:// opening; JSON remains source of truth."""
import json,pathlib,runpy
ROOT=pathlib.Path(__file__).resolve().parents[1]
runpy.run_path(str(ROOT/"tools/validate_data.py"),run_name="__main__")
catalog=json.loads((ROOT/"data/catalog.json").read_text(encoding="utf-8"))
sets=[json.loads((ROOT/item["file"]).read_text(encoding="utf-8")) for item in catalog["sets"]]
target=ROOT/"data/generated/sets.js"
target.parent.mkdir(parents=True,exist_ok=True)
target.write_text("// Generated by tools/build_local.py; edit data/sets/*.json instead.\nwindow.KA_SETS = "+json.dumps(sets,ensure_ascii=False,indent=2)+";\n",encoding="utf-8")
core=(ROOT/"site/js/core.js").read_text(encoding="utf-8").replace("export ","")
app=(ROOT/"site/js/app.js").read_text(encoding="utf-8").split("\n",1)[1]
(ROOT/"site/js/app.bundle.js").write_text("// Generated by tools/build_local.py; edit app.js and core.js instead.\n(function(){\n"+core+"\n"+app+"\n})();\n",encoding="utf-8")
print("OK: direct-open scripts generated")
